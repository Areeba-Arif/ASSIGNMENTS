// Question 1 - JavaScript Operators

// Two number variables
let num1 = 10;
let num2 = 5;

// Arithmetic Operators
console.log("Addition:", num1 + num2);
console.log("Subtraction:", num1 - num2);
console.log("Multiplication:", num1 * num2);
console.log("Division:", num1 / num2);
console.log("Modulus:", num1 % num2);

// Increment
let incrementNumber = 10;
console.log("Before Increment:", incrementNumber);
incrementNumber++;
console.log("After Increment:", incrementNumber);

// Decrement
let decrementNumber = 10;
console.log("Before Decrement:", decrementNumber);
decrementNumber--;
console.log("After Decrement:", decrementNumber);


// Assignment Operators
let value = 20;

console.log("Initial Value:", value);

value += 5;
console.log("After += 5:", value);

value -= 3;
console.log("After -= 3:", value);

value *= 2;
console.log("After *= 2:", value);

value /= 2;
console.log("After /= 2:", value);


// Comparison Operators
console.log("num1 == num2:", num1 == num2);
console.log("num1 === num2:", num1 === num2);
console.log("num1 != num2:", num1 != num2);
console.log("num1 !== num2:", num1 !== num2);
console.log("num1 > num2:", num1 > num2);
console.log("num1 < num2:", num1 < num2);
console.log("num1 >= num2:", num1 >= num2);
console.log("num1 <= num2:", num1 <= num2);