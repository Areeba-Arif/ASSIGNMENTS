// Create an array named fruits containing at least 5 fruit names
const fruits = ["Apple", "Banana", "Mango", "Orange", "Strawberry"];

console.log("--- Question 1: Basic Array Methods ---");

// Use length to display the number of elements
console.log("Number of fruits :", fruits.length);

// Use toString() to convert the array into a string
console.log("Fruits as a string :", fruits.toString());

// Use at() to access at least two elements using indexes
console.log("Fruit at index 1 :", fruits.at(1));
console.log("Fruit at index 3 :", fruits.at(3));

// Use join() to display the elements separated by a symbol or text
console.log("Fruits joined with ' - ' :", fruits.join(" - "));